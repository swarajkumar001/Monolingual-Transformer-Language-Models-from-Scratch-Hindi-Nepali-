"""Collect every reportable number from the result files into one sheet.

Writing the final report means quoting perhaps eighty numbers. Hunting them
through a dozen JSON files while writing is how transcription errors get into a
submission, so this pulls them all from the actual artifacts into one document.

Every value is read from a file produced by a run. Nothing here is typed by
hand, so the sheet cannot disagree with the results it summarises.

Run from the branch that has the bonus results if you want the ablation section
included; it is skipped with a note otherwise.

    python scripts/make_numbers_sheet.py
"""

from __future__ import annotations

import json
import math
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUT = REPO_ROOT / "docs" / "report_numbers.md"


def load(path: Path):
    """Read a JSON file, or return None if it is not on this branch."""
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def fmt(value: float, places: int = 4) -> str:
    """Format a float at a fixed number of decimal places."""
    return f"{value:.{places}f}"


def main() -> None:
    """Assemble the sheet and write it."""
    sys.stdout.reconfigure(encoding="utf-8")
    out: list[str] = []
    add = out.append

    p2 = REPO_ROOT / "report" / "phase2"
    p3 = REPO_ROOT / "report" / "phase3"
    bonus = REPO_ROOT / "report" / "bonus"

    h_eval, n_eval = load(p2 / "hindi_eval.json"), load(p2 / "nepali_eval.json")
    h_attn, n_attn = load(p2 / "hindi_attention.json"), load(p2 / "nepali_attention.json")
    tok = load(REPO_ROOT / "report" / "phase1" / "measured_tokenizer_metrics.json")

    add("# Report numbers — every figure, from the result files\n")
    add("Generated by `scripts/make_numbers_sheet.py`. Every value is read from "
        "a file produced by an actual run; none is typed by hand.\n")
    add("Use this while writing so you are not hunting through JSON. **The prose "
        "is yours to write** — this sheet is only the arithmetic.\n")

    # ---- Phase 1 -----------------------------------------------------------
    add("\n---\n\n## Phase 1 — corpora and tokenizers\n")
    add("| | Model H (Hindi) | Model L (Nepali) |")
    add("|---|---:|---:|")
    if h_eval and n_eval:
        hc, nc = h_eval["corpus"], n_eval["corpus"]
        for split in ("train", "val", "test"):
            if split in hc and split in nc:
                add(f"| {split} tokens | {hc[split].get('tokens', 0):,} "
                    f"| {nc[split].get('tokens', 0):,} |")
    add("| Tokenizer | SentencePiece Unigram | SentencePiece BPE |")
    add("| Vocabulary | 8,000 | 10,000 |")

    if tok:
        add("\n### Tokenizer sweep (measured)\n")
        add("| Language | Vocab | chars/token | fertility | unk rate | byte fallback |")
        add("|---|---:|---:|---:|---:|---:|")
        for lang in ("hindi", "nepali"):
            for row in tok.get(lang, []):
                add(f"| {lang} | {row['vocab_size']:,} "
                    f"| {row['chars_per_token']:.4f} "
                    f"| {row['fertility_tokens_per_word']:.4f} "
                    f"| {row['unk_rate']:.6f} "
                    f"| {row['byte_fallback_rate']:.6f} |")
        add("\n**The chosen vocabularies are Hindi 8,000 and Nepali 10,000.** "
            "Note Nepali's byte-fallback rate is 0.0 at every size — that is the "
            "defect, not a good score: it has no byte fallback, which is why its "
            "unk rate is non-zero.\n")

    add("\n### Splits\n")
    add("| | Hindi | Nepali |")
    add("|---|---|---|")
    add("| Ratio | 96 / 2 / 2 | 85 / 7.5 / 7.5 |")
    add("| Seed | 42 | 20260817 |")
    add("| Method | shuffle then slice | deterministic hash of doc_id |")
    add("| Held out before quality filtering | no | **yes** (stage S07) |")
    add("| Train/test decontamination | — | MinHash, removes from train only |")

    # ---- Phase 2 -----------------------------------------------------------
    add("\n---\n\n## Phase 2 — model, training, evaluation\n")
    if h_eval and n_eval:
        hp, np_ = h_eval["parameter_count"], n_eval["parameter_count"]
        add("| | Model H | Model L |")
        add("|---|---:|---:|")
        add(f"| Total parameters | {hp['total']:,} | {np_['total']:,} |")
        add(f"| Embedding | {hp['embedding']:,} | {np_['embedding']:,} |")
        add(f"| **Non-embedding** | **{hp['non_embedding']:,}** "
            f"| **{np_['non_embedding']:,}** |")
        add(f"| Evaluated checkpoint step | {h_eval['checkpoint_step']:,} "
            f"| {n_eval['checkpoint_step']:,} |")

        mc = h_eval["model_config"]
        add(f"\nArchitecture (identical for both): {mc['n_layer']} layers, "
            f"{mc['n_head']} heads, d={mc['n_embd']}, d_ff={mc['d_ff']}, "
            f"context {mc['block_size']}, dropout {mc['dropout']}, "
            f"weight tying {mc['tie_weights']}, positions `{mc['pos_encoding']}`.\n")

        add("\n### Intrinsic (test split)\n")
        add("| | Model H | Model L |")
        add("|---|---:|---:|")
        hi, ni = h_eval["intrinsic"], n_eval["intrinsic"]
        add(f"| Cross-entropy (nats) | {fmt(hi['cross_entropy_nats'])} "
            f"| {fmt(ni['cross_entropy_nats'])} |")
        add(f"| Perplexity | {fmt(hi['perplexity'], 2)} | {fmt(ni['perplexity'], 2)} |")
        add(f"| Bits per token | {fmt(hi['bits_per_token'])} | {fmt(ni['bits_per_token'])} |")
        add(f"| **Bits per byte** | **{fmt(hi['bits_per_byte'])}** "
            f"| **{fmt(ni['bits_per_byte'])}** |")
        add(f"| Tokens scored | {hi['tokens_scored']:,} | {ni['tokens_scored']:,} |")
        add(f"| Bytes scored | {hi['bytes_scored']:,} | {ni['bytes_scored']:,} |")
        hb = hi["bytes_scored"] / hi["tokens_scored"]
        nb = ni["bytes_scored"] / ni["tokens_scored"]
        add(f"| Bytes per token | {hb:.3f} | {nb:.3f} |")
        add(f"\nThe BPB arithmetic: {fmt(hi['bits_per_token'])} bits/token ÷ "
            f"{hb:.2f} bytes/token = {fmt(hi['bits_per_byte'])} for H, and "
            f"{fmt(ni['bits_per_token'])} ÷ {nb:.2f} = "
            f"{fmt(ni['bits_per_byte'])} for L.\n")

        add("\n### Generation\n")
        add("| Decoding | H chrF++ | L chrF++ | H BLEU | L BLEU "
            "| H repetition | L repetition | H distinct-1 | L distinct-1 |")
        add("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
        hg, ng = h_eval["generation"]["settings"], n_eval["generation"]["settings"]
        for label in hg:
            if label not in ng:
                continue
            a, b = hg[label], ng[label]
            add(f"| {label} | {a['chrf_pp']:.2f} | {b['chrf_pp']:.2f} "
                f"| {a['bleu']:.2f} | {b['bleu']:.2f} "
                f"| {a['repetition_rate']:.3f} | {b['repetition_rate']:.3f} "
                f"| {a['distinct_1']:.3f} | {b['distinct_1']:.3f} |")

    if h_attn and n_attn:
        add("\n### Attention\n")
        add("| | Model H | Model L |")
        add("|---|---:|---:|")
        add(f"| Mean entropy (nats) | {fmt(h_attn['mean_entropy'])} "
            f"| {fmt(n_attn['mean_entropy'])} |")
        add(f"| Uniform baseline | {fmt(h_attn['uniform_baseline_entropy'])} "
            f"| {fmt(n_attn['uniform_baseline_entropy'])} |")
        add(f"| Mean distance (tokens) | {fmt(h_attn['mean_distance'], 2)} "
            f"| {fmt(n_attn['mean_distance'], 2)} |")
        add(f"| Local-head fraction | {fmt(h_attn['local_head_fraction'])} "
            f"| {fmt(n_attn['local_head_fraction'])} |")

        add("\nSharpest head per layer (entropy @ mean distance):\n")
        add("| Layer | Model H | Model L |")
        add("|---|---|---|")
        for lh, ln in zip(h_attn["layers"], n_attn["layers"]):
            ih = min(range(len(lh["entropy"])), key=lambda i: lh["entropy"][i])
            inn = min(range(len(ln["entropy"])), key=lambda i: ln["entropy"][i])
            add(f"| {lh['layer']} | {lh['entropy'][ih]:.2f} @ "
                f"{lh['mean_distance'][ih]:.1f} | {ln['entropy'][inn]:.2f} @ "
                f"{ln['mean_distance'][inn]:.1f} |")

    # ---- Phase 3 -----------------------------------------------------------
    add("\n---\n\n## Phase 3 — reasoning finetuning\n")
    stats_h = load(REPO_ROOT / "hindi" / "reasoning" / "data" / "dataset_stats.json")
    stats_n = load(REPO_ROOT / "nepali" / "reasoning" / "data" / "dataset_stats.json")
    if stats_h and stats_n:
        add("| | Hindi | Nepali |")
        add("|---|---:|---:|")
        for split in ("train", "val", "test"):
            add(f"| {split} examples | {stats_h['splits'][split]['examples']:,} "
                f"| {stats_n['splits'][split]['examples']:,} |")
        for split in ("train", "val", "test"):
            add(f"| {split} templates | {stats_h['splits'][split]['distinct_templates']} "
                f"| {stats_n['splits'][split]['distinct_templates']} |")
        lk = stats_h["leakage_check"]
        add(f"| Entity names train/val/test | {lk['train_names']}/{lk['val_names']}"
            f"/{lk['test_names']} | same |")
        add(f"| Names disjoint across splits | {lk['entity_names_disjoint_across_splits']} "
            f"| {stats_n['leakage_check']['entity_names_disjoint_across_splits']} |")
        add(f"| Templates disjoint | {lk['templates_disjoint_across_splits']} "
            f"| {stats_n['leakage_check']['templates_disjoint_across_splits']} |")

    rows = {}
    for lang in ("hindi", "nepali"):
        for stage in ("pretrained", "finetuned"):
            rows[(lang, stage)] = load(p3 / f"{lang}_reasoning_{stage}.json")
    if all(rows.values()):
        add("\n### Reasoning accuracy\n")
        add("| | H pretrained | H finetuned | L pretrained | L finetuned |")
        add("|---|---:|---:|---:|---:|")
        def g(d, *keys):
            for k in keys:
                if isinstance(d, dict) and k in d:
                    d = d[k]
                else:
                    return None
            return d
        for label, path in (("Exact match", ("exact_match", "accuracy")),
                            ("Forced choice", ("forced_choice", "accuracy")),
                            ("Chance rate", ("forced_choice", "chance_accuracy")),
                            ("Answer-token loss", ("answer_token_loss",
                                                   "answer_token_loss")),
                            ("Answer-token perplexity",
                             ("answer_token_loss", "answer_token_perplexity"))):
            vals = []
            for lang in ("hindi", "nepali"):
                for stage in ("pretrained", "finetuned"):
                    v = g(rows[(lang, stage)], *path)
                    vals.append("—" if v is None else f"{v:.4f}")
            add(f"| {label} | {vals[0]} | {vals[1]} | {vals[2]} | {vals[3]} |")
        add("\n### Per-task exact match, finetuned\n")
        add("| Task | Model H | Model L |")
        add("|---|---:|---:|")
        hb = rows[("hindi", "finetuned")]["exact_match"]["by_task"]
        nb = rows[("nepali", "finetuned")]["exact_match"]["by_task"]
        for task in sorted(hb):
            add(f"| {task} | {hb[task]['accuracy']:.4f} "
                f"| {nb[task]['accuracy']:.4f} |")

        add("\n### Per-task forced choice, finetuned (chance = 0.4167)\n")
        add("| Task | Model H | Model L |")
        add("|---|---:|---:|")
        hf = rows[("hindi", "finetuned")]["forced_choice"]["by_task"]
        nf = rows[("nepali", "finetuned")]["forced_choice"]["by_task"]
        for task in sorted(hf):
            add(f"| {task} | {hf[task]['accuracy']:.4f} "
                f"| {nf[task]['accuracy']:.4f} |")

        add("\n### Off-prompt answer rate\n")
        add("| Task | H pretrained | H finetuned | L pretrained | L finetuned |")
        add("|---|---:|---:|---:|---:|")
        for task in sorted(rows[("hindi", "finetuned")]["error_analysis"]):
            cells = []
            for lang in ("hindi", "nepali"):
                for stage in ("pretrained", "finetuned"):
                    ea = rows[(lang, stage)]["error_analysis"][task]
                    value = ea.get("answered_off_prompt")
                    cells.append("—" if value is None else f"{value:.4f}")
            add(f"| {task} | {cells[0]} | {cells[1]} | {cells[2]} | {cells[3]} |")

    # ---- Bonus -------------------------------------------------------------
    add("\n---\n\n## Bonus — no positional embeddings\n")
    abl = load(bonus / "ablation_comparison.json")
    if abl is None:
        add("*Not on this branch. Run this script from `bonus-no-pos` to include it.*\n")
    else:
        add(f"Matched step: **{abl['matched_step']:,}**\n")
        add("| | standard | ablated |")
        add("|---|---:|---:|")
        s, a = abl["runs"]["standard"], abl["runs"]["ablated"]
        add(f"| Final step reached | {s['final_step']:,} | {a['final_step']:,} |")
        add(f"| Val loss @ matched step | {fmt(s['val_loss_at_matched_step'])} "
            f"| {fmt(a['val_loss_at_matched_step'])} |")
        add(f"| Val perplexity @ matched step | {fmt(s['val_ppl_at_matched_step'], 2)} "
            f"| {fmt(a['val_ppl_at_matched_step'], 2)} |")
        if "intrinsic" in s and "intrinsic" in a:
            add(f"| Test perplexity | {fmt(s['intrinsic']['perplexity'], 2)} "
                f"| {fmt(a['intrinsic']['perplexity'], 2)} |")
            add(f"| Test bits-per-byte | {fmt(s['intrinsic']['bits_per_byte'])} "
                f"| {fmt(a['intrinsic']['bits_per_byte'])} |")
        if "parameter_count" in s and "parameter_count" in a:
            add(f"| Total parameters | {s['parameter_count']['total']:,} "
                f"| {a['parameter_count']['total']:,} |")
            add(f"| Non-embedding | {s['parameter_count']['non_embedding']:,} "
                f"| {a['parameter_count']['non_embedding']:,} |")
        if "attention" in s and "attention" in a:
            add(f"| Attention mean entropy | {fmt(s['attention']['mean_entropy'])} "
                f"| {fmt(a['attention']['mean_entropy'])} |")
            add(f"| Attention mean distance | {fmt(s['attention']['mean_distance'], 2)} "
                f"| {fmt(a['attention']['mean_distance'], 2)} |")
            add(f"| Local-head fraction | {fmt(s['attention']['local_head_fraction'])} "
                f"| {fmt(a['attention']['local_head_fraction'])} |")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}  ({len('\n'.join(out))/1024:.1f} KB)")


if __name__ == "__main__":
    main()
